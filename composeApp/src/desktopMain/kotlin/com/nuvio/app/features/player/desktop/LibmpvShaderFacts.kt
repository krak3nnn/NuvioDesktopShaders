package com.nuvio.app.features.player.desktop

import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.attribute.BasicFileAttributes
import java.util.concurrent.ConcurrentHashMap
import kotlin.io.path.useLines

// Fork-only: what the scanner needs to know about a shader file, collected in one streaming pass.
internal class LibmpvShaderFacts(
    val hasHook: Boolean,
    val hasTexture: Boolean,
    val retroArch: Boolean,
    val gpuNext: Boolean,
    val rgb8: Boolean,
    val textures: Set<String>,
    val saves: Set<String>,
    val binds: Set<String>,
) {
    companion object {
        private const val MPV_LIBRETRO_MARKER = "// Generated by mpv-libretro"
        private val RETROARCH_MARKERS = listOf("#pragma parameter", "#pragma stage", "#if defined(VERTEX)", "#ifdef VERTEX")

        private class Cached(val size: Long, val modified: Long, val facts: LibmpvShaderFacts)

        // Files are only re-read when they change; a full mpv-retro-shaders folder is ~30 MB.
        private val cache = ConcurrentHashMap<Path, Cached>()

        // Null when the file can't be read.
        fun of(file: Path): LibmpvShaderFacts? = runCatching {
            val attributes = Files.readAttributes(file, BasicFileAttributes::class.java)
            val size = attributes.size()
            val modified = attributes.lastModifiedTime().toMillis()
            cache[file]?.takeIf { it.size == size && it.modified == modified }?.facts
                ?: read(file).also { cache[file] = Cached(size, modified, it) }
        }.getOrNull()

        fun read(file: Path): LibmpvShaderFacts {
            var hasHook = false
            var hasTexture = false
            var retroArch = false
            var gpuNext = false
            var rgb8 = false
            val textures = mutableSetOf<String>()
            val saves = mutableSetOf<String>()
            val binds = mutableSetOf<String>()
            file.useLines { lines ->
                for (line in lines) {
                    if (line.startsWith("//!")) {
                        val argument = line.substringAfter(' ', "").trim()
                        when (line.substringBefore(' ').trimEnd()) {
                            "//!HOOK" -> hasHook = true
                            "//!TEXTURE" -> { hasTexture = true; if (argument.isNotEmpty()) textures += argument }
                            "//!SAVE" -> if (argument.isNotEmpty()) saves += argument
                            "//!BIND" -> if (argument.isNotEmpty()) binds += argument
                            "//!PARAM" -> gpuNext = true
                            "//!FORMAT" -> if (argument == "rgb8") rgb8 = true
                        }
                    } else if (line.startsWith(MPV_LIBRETRO_MARKER)) {
                        // mpv-libretro output targets gpu-next even when it has no //!PARAM blocks.
                        gpuNext = true
                    } else if (!hasHook && !hasTexture && RETROARCH_MARKERS.any { it in line }) {
                        retroArch = true
                    }
                }
            }
            return LibmpvShaderFacts(hasHook, hasTexture, retroArch, gpuNext, rgb8, textures, saves, binds)
        }
    }
}
